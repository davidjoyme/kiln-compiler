# File: kiln/gpu/codegen.py
"""Generate Triton kernels for NVIDIA GPUs from an optimised Kiln graph.

The GPU backend reuses everything above code generation: freezing, fusion,
buffer assignment and memory planning run exactly as for the CPU. Only the
last step differs: instead of lowering each kernel through MLIR, Kiln writes
it as a Triton kernel, the same split TorchInductor uses (one graph-level
optimiser, a C++ backend for CPU and a Triton backend for GPU).

Shapes are static, so every size, stride and buffer offset is a constant in
the generated source. Views (transposes, slices, broadcasts) are just
different strides: a transposed matmul operand or a broadcast bias is a
strided load, never a copy.

One Triton kernel per Kiln kernel, of four kinds:

  elementwise  a flat 1-D loop over the output, BLOCK elements per program.
               Every intermediate lives in registers. A kernel whose outputs
               have different shapes gets one Triton kernel per output, each
               recomputing what it needs (cheap: elementwise ops are free next
               to memory traffic).

  row          LayerNorm / softmax: one program per row. If the row fits in
               one block (<= MAX_ROW_BLOCK floats) it's loaded once and every
               op runs on registers. Longer rows are processed in chunks, one
               pass per level of reduction, recomputing elementwise values
               from the inputs in each pass rather than storing them:
               memory use stays constant however long the row is.

  matmul       tensor-core tiles via tl.dot, BM x BN per program, a loop over
               K in BK steps, and the fused epilogue (bias, GELU, residual,
               scaling, masking) applied to the accumulator tile in registers
               before the single store.

  reduction    any other reduction (e.g. over a leading dim): each program
               computes BLOCK_O outputs, looping over the reduced extent.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from math import prod

from kiln.ir import ops
from kiln.ir.core import Graph, Kernel
from kiln.passes.buffers import compute_layouts, kernel_inputs, kernel_outputs
from kiln.passes.fusion import is_row_reduction

MAX_ROW_BLOCK = 4096        # rows up to this many floats are kept in registers
ELEMENTWISE_BLOCK = 1024
INT32_LIMIT = 2**31 - 1

PRELUDE = '''# Generated by Kiln. Do not edit: regenerate with kiln.compile(..., device="cuda").
import triton
import triton.language as tl


@triton.jit
def _tanh(x):
    e = tl.exp(-2.0 * tl.abs(x))
    t = (1.0 - e) / (1.0 + e)
    return tl.where(x < 0.0, -t, t)


@triton.jit
def _sigmoid(x):
    return 1.0 / (1.0 + tl.exp(-x))


@triton.jit
def _erf(x):
    # Abramowitz & Stegun 7.1.26 (max error 1.5e-7), same as the CPU backend.
    a = tl.abs(x)
    t = 1.0 / (1.0 + 0.3275911 * a)
    p = t * (0.254829592 + t * (-0.284496736 + t * (1.421413741 + t * (-1.453152027 + t * 1.061405429))))
    y = 1.0 - p * tl.exp(-a * a)
    return tl.where(x < 0.0, -y, y)


@triton.jit
def _gelu_tanh(x):
    return 0.5 * x * (1.0 + _tanh(0.7978845608028654 * (x + 0.044715 * x * x * x)))


@triton.jit
def _gelu_erf(x):
    return 0.5 * x * (1.0 + _erf(x * 0.7071067811865476))
'''


def next_pow2(n):
    p = 1
    while p < n:
        p *= 2
    return p


def literal(x: float) -> str:
    if x == float("inf"):
        return 'float("inf")'
    if x == float("-inf"):
        return 'float("-inf")'
    return repr(float(x))


@dataclass
class Launch:
    """One Triton kernel launch: function name, grid, base pointers, options."""

    name: str
    grid: tuple
    bases: list                 # ("input", i) | ("output", i) | ("const", name) | ("arena",)
    num_warps: int = 4
    num_stages: int | None = None
    kind: str = ""
    kernel: str = ""            # the Kiln kernel it comes from


@dataclass
class Program:
    source: str
    launches: list = field(default_factory=list)


class _Code:
    """Lines of a kernel body. ``nested()`` opens an indented block (a loop body)
    that shares the same output and the same counter for fresh names."""

    def __init__(self, lines=None, indent=1, counter=None):
        self.lines = [] if lines is None else lines
        self.indent = indent
        self._counter = counter if counter is not None else [0]

    def fresh(self, prefix="v"):
        self._counter[0] += 1
        return f"{prefix}{self._counter[0]}"

    def emit(self, line, extra=0):
        self.lines.append("    " * (self.indent + extra) + line)

    def nested(self):
        return _Code(self.lines, self.indent + 1, self._counter)


class _KernelWriter:
    """Writes the Triton source for one Kiln kernel."""

    def __init__(self, graph: Graph, kernel: Kernel, layouts, allow_tf32: bool):
        self.g = graph
        self.k = kernel
        self.layouts = layouts
        self.allow_tf32 = allow_tf32
        self.members = set(kernel.nodes)
        self.inputs = kernel_inputs(graph, kernel)
        self.outputs = kernel_outputs(graph, kernel)

    # -- buffers and addressing -------------------------------------------------------

    def base_key(self, v):
        b = self.layouts[v].base
        return ("arena",) if b[0] == "arena" else b

    def bases(self):
        """The distinct buffers this kernel touches, in parameter order."""
        keys = []
        for v in self.inputs + self.outputs:
            key = self.base_key(v)
            if key not in keys:
                keys.append(key)
        return keys

    def param(self, key):
        if not hasattr(self, "_params"):
            self._params, consts = {}, 0
            for b in self.bases():
                if b[0] == "const":
                    self._params[b] = f"c_{consts}"
                    consts += 1
                elif b[0] == "arena":
                    self._params[b] = "arena"
                else:
                    self._params[b] = f"{'in' if b[0] == 'input' else 'out'}_{b[1]}"
        return self._params[key]

    def element_offset(self, v):
        lay = self.layouts[v]
        if lay.base[0] == "arena":
            return v_offset_elements(lay)
        return lay.offset

    def needs_int64(self, v):
        lay = self.layouts[v]
        span = self.element_offset(v) + sum((s - 1) * st for s, st in zip(lay.shape, lay.strides))
        return span > INT32_LIMIT

    def address(self, v, index, shape_of=None):
        """Pointer expression for value ``v`` at iteration indices ``index``.

        ``index`` holds one expression per iteration dim (right-aligned with
        v's dims; broadcast dims of v contribute nothing). ``shape_of`` is an
        expression with the shape of the whole tile: it's added times 0 so the
        pointer always has the tile's shape. Triton requires that for stores,
        and a size-1 output (a [1, n] matmul result for a single token, or a
        [1, 1] value) would otherwise give a pointer of the wrong shape.
        """
        lay = self.layouts[v]
        terms = []
        off = self.element_offset(v)
        if off:
            terms.append(str(off))
        rank_it = len(index)
        for i, (size, stride) in enumerate(zip(lay.shape, lay.strides)):
            j = rank_it - len(lay.shape) + i
            if size == 1 or stride == 0 or j < 0 or index[j] is None:
                continue
            terms.append(f"{index[j]} * {stride}" if stride != 1 else f"{index[j]}")
        if shape_of is not None:
            terms.append(f"{shape_of} * 0")
        return f"{self.param(self.base_key(v))} + ({' + '.join(terms) if terms else '0'})"

    # -- scalar ops -----------------------------------------------------------------------

    def apply(self, n, args):
        op = n.op
        binary = {"add": "+", "sub": "-", "mul": "*", "div": "/"}
        if op in binary:
            return f"({args[0]} {binary[op]} {args[1]})"
        if op == "maximum":
            return f"tl.maximum({args[0]}, {args[1]})"
        if op == "minimum":
            return f"tl.minimum({args[0]}, {args[1]})"
        if op == "neg":
            return f"(-{args[0]})"
        if op == "relu":
            return f"tl.maximum({args[0]}, 0.0)"
        if op == "exp":
            return f"tl.exp({args[0]})"
        if op in ("tanh", "sigmoid", "erf"):
            return f"_{op}({args[0]})"
        if op == "gelu":
            return f"_gelu_{'tanh' if n.attrs.get('approximate', 'none') == 'tanh' else 'erf'}({args[0]})"
        if op == "rsqrt":
            return f"tl.rsqrt({args[0]})"
        if op == "sqrt":
            return f"tl.sqrt({args[0]})"
        if op == "copy":
            return args[0]
        raise NotImplementedError(f"GPU backend: no lowering for '{op}'")

    def operand(self, code, env, v, load):
        """Expression for value v: computed in this kernel, a scalar constant, or loaded."""
        if v in env:
            return env[v]
        if self.g.is_scalar_const(v):
            return literal(float(self.g.const_data(v)))
        name = code.fresh("x")
        code.emit(f"{name} = {load(v)}")
        env[v] = name
        return name

    def compute(self, code, env, wanted, load, skip=()):
        """Emit every kernel node needed for ``wanted``, in topological order."""
        needed = set()
        stack = list(wanted)
        while stack:
            v = stack.pop()
            if v in env or v in needed or v.node not in self.members or v.node in skip:
                continue
            needed.add(v)
            stack.extend(v.node.inputs)
        for n in self.k.nodes:
            if n.out in needed:
                args = [self.operand(code, env, v, load) for v in n.inputs]
                name = code.fresh()
                code.emit(f"{name} = {self.apply(n, args)}")
                env[n.out] = name

    # -- kernel kinds ---------------------------------------------------------------------

    def signature(self, name):
        params = ", ".join(self.param(k) for k in self.bases())
        return [f"@triton.jit", f"def {name}({params}):"]

    def elementwise(self, out, name):
        shape = out.shape
        numel = prod(shape) or 1
        code = _Code()
        wide = any(self.needs_int64(v) for v in self.inputs + self.outputs) or numel > INT32_LIMIT
        code.emit("pid = tl.program_id(0)")
        code.emit(f"offs = pid * {ELEMENTWISE_BLOCK} + tl.arange(0, {ELEMENTWISE_BLOCK})")
        if wide:
            code.emit("offs = offs.to(tl.int64)")
        code.emit(f"mask = offs < {numel}")
        index, rest = [], "offs"
        for d in range(len(shape) - 1, -1, -1):
            if shape[d] == 1:
                index.append(None)
                continue
            stride = prod(shape[d + 1:])
            expr = f"({rest} // {stride})" if stride > 1 else rest
            index.append(f"({expr} % {shape[d]})" if d > 0 else expr)
        index.reverse()
        code.emit("# indices: " + ", ".join(i or "0" for i in index))
        load = lambda v: f"tl.load({self.address(v, index, 'offs')}, mask=mask, other=0.0)"
        env = {}
        self.compute(code, env, [out], load)
        val = self.operand(code, env, out, load)
        code.emit(f"tl.store({self.address(out, index, 'offs')}, {val}, mask=mask)")
        grid = (-(-numel // ELEMENTWISE_BLOCK),)
        return self.signature(name) + code.lines, Launch(name, grid, self.bases(), 4, None, "elementwise", self.k.name)

    def row(self, name):
        reductions = [n for n in self.k.nodes if n.op.startswith("reduce_")]
        shape = reductions[0].inputs[0].shape
        rows_shape, inner = shape[:-1], shape[-1]
        n_rows = prod(rows_shape) or 1
        block = min(next_pow2(inner), MAX_ROW_BLOCK)
        chunked = next_pow2(inner) > MAX_ROW_BLOCK
        code = _Code()
        code.emit("row = tl.program_id(0)")
        row_index, rest = [], "row"
        for d in range(len(rows_shape) - 1, -1, -1):
            if rows_shape[d] == 1:
                row_index.append(None)
                continue
            stride = prod(rows_shape[d + 1:])
            expr = f"({rest} // {stride})" if stride > 1 else rest
            row_index.append(f"({expr} % {rows_shape[d]})" if d > 0 else expr)
        row_index.reverse()
        if any(self.needs_int64(v) for v in self.inputs + self.outputs):
            code.emit("row = row.to(tl.int64)")

        def is_vector(v):            # varies along the row (vs one value per row)
            return v.shape[-1] != 1 if v.type.rank else False

        def index_for(v, cols):
            return row_index + [cols if is_vector(v) else None]

        def loader(cols, mask):
            def load(v):
                if is_vector(v):
                    return f"tl.load({self.address(v, index_for(v, cols))}, mask={mask}, other=0.0)"
                return f"tl.load({self.address(v, index_for(v, cols))})"
            return load

        stores = []
        env = {}       # per-row scalars (and, unchunked, the vectors too)

        def reduce_expr(n, vec, mask):
            if n.op == "reduce_sum":
                return f"tl.sum(tl.where({mask}, {vec}, 0.0), axis=0)"
            return f"tl.max(tl.where({mask}, {vec}, float(\"-inf\")), axis=0)"

        if not chunked:
            code.emit(f"cols = tl.arange(0, {block})")
            code.emit(f"mask = cols < {inner}")
            load = loader("cols", "mask")
            for n in self.k.nodes:
                args = [self.operand(code, env, v, load) for v in n.inputs]
                name_ = code.fresh()
                if n.op.startswith("reduce_"):
                    code.emit(f"{name_} = {reduce_expr(n, args[0], 'mask')}")
                else:
                    code.emit(f"{name_} = {self.apply(n, args)}")
                env[n.out] = name_
            for v in self.outputs:
                if is_vector(v):
                    code.emit(f"tl.store({self.address(v, index_for(v, 'cols'))}, {env[v]}, mask=mask)")
                else:
                    code.emit(f"tl.store({self.address(v, index_for(v, 'cols'))}, {env[v]})")
        else:
            # Long rows: one pass over the row per level of reduction (LayerNorm
            # has 2: mean, then variance; softmax has 2: max, then sum), plus a
            # final pass that writes the outputs. Elementwise values are
            # recomputed from the inputs in every pass instead of being stored,
            # so registers and memory use stay constant for any row length.
            level = {}
            for n in self.k.nodes:
                deps = [level[v] for v in n.inputs if v in level]
                level[n.out] = max(deps, default=0) + (1 if n.op.startswith("reduce_") else 0)
            depth = max(level.values())
            scalar_load = loader("0", "True")

            def scalars_at(lvl):
                return [n.out for n in self.k.nodes
                        if level[n.out] == lvl and not is_vector(n.out) and not n.op.startswith("reduce_")]

            later = lambda lvl: [n for n in self.k.nodes if level[n.out] > lvl or is_vector(n.out)]
            self.compute(code, env, scalars_at(0), scalar_load, skip=later(0))
            for p in range(depth):
                reds = [n for n in reductions if level[n.out] == p + 1]
                accs = {}
                for n in reds:
                    accs[n] = code.fresh("acc")
                    init = "0.0" if n.op == "reduce_sum" else 'float("-inf")'
                    code.emit(f"{accs[n]} = tl.full([{block}], {init}, tl.float32)")
                code.emit(f"for c0 in range(0, {inner}, {block}):")
                body = code.nested()
                body.emit(f"cols = c0 + tl.arange(0, {block})")
                body.emit(f"mask = cols < {inner}")
                local, load = dict(env), loader("cols", "mask")
                self.compute(body, local, [n.inputs[0] for n in reds], load,
                             skip=[m for m in self.k.nodes if level[m.out] > p])
                for n in reds:
                    vec = self.operand(body, local, n.inputs[0], load)
                    if n.op == "reduce_sum":
                        body.emit(f"{accs[n]} = {accs[n]} + tl.where(mask, {vec}, 0.0)")
                    else:
                        body.emit(f'{accs[n]} = tl.maximum({accs[n]}, tl.where(mask, {vec}, float("-inf")))')
                for n in reds:
                    env[n.out] = code.fresh()
                    fn = "tl.sum" if n.op == "reduce_sum" else "tl.max"
                    code.emit(f"{env[n.out]} = {fn}({accs[n]}, axis=0)")
                self.compute(code, env, scalars_at(p + 1), scalar_load, skip=later(p + 1))
            for v in self.outputs:
                if not is_vector(v):
                    code.emit(f"tl.store({self.address(v, index_for(v, '0'))}, {env[v]})")
            vec_outs = [v for v in self.outputs if is_vector(v)]
            if vec_outs:
                code.emit(f"for c0 in range(0, {inner}, {block}):")
                body = code.nested()
                body.emit(f"cols = c0 + tl.arange(0, {block})")
                body.emit(f"mask = cols < {inner}")
                local, load = dict(env), loader("cols", "mask")
                self.compute(body, local, vec_outs, load)
                for v in vec_outs:
                    body.emit(f"tl.store({self.address(v, index_for(v, 'cols'))}, "
                              f"{self.operand(body, local, v, load)}, mask=mask)")
        warps = 4 if block <= 1024 else 8
        return self.signature(name) + code.lines, Launch(name, (n_rows,), self.bases(), warps, None, "row", self.k.name)

    def reduction(self, name):
        (n,) = [m for m in self.k.nodes]
        x = n.inputs[0]
        dims = set(n.attrs["dims"])
        out = n.out
        kept = [d for d in range(x.type.rank) if d not in dims and x.shape[d] != 1]
        red = [d for d in sorted(dims) if x.shape[d] != 1]
        n_out = prod(out.shape) or 1
        r_total = prod(x.shape[d] for d in red) if red else 1
        bo, br = 64, min(next_pow2(r_total), 64)
        code = _Code()
        code.emit("pid = tl.program_id(0)")
        code.emit(f"o = pid * {bo} + tl.arange(0, {bo})")
        if self.needs_int64(x) or self.needs_int64(out):
            code.emit("o = o.to(tl.int64)")
        code.emit(f"omask = o < {n_out}")
        init = "0.0" if n.op == "reduce_sum" else 'float("-inf")'
        code.emit(f"acc = tl.full([{bo}, {br}], {init}, tl.float32)")
        code.emit(f"for r0 in range(0, {r_total}, {br}):")
        loop = code.nested()
        loop.emit(f"r = r0 + tl.arange(0, {br})")
        loop.emit(f"rmask = r < {r_total}")
        index = [None] * x.type.rank

        def decompose(var, dimlist, shape_of):
            rest, parts = var, {}
            for i in range(len(dimlist) - 1, -1, -1):
                d = dimlist[i]
                stride = prod(shape_of[e] for e in dimlist[i + 1:])
                expr = f"({rest} // {stride})" if stride > 1 else rest
                parts[d] = f"({expr} % {shape_of[d]})" if i > 0 else expr
            return parts

        for d, e in decompose("o", kept, x.shape).items():
            index[d] = f"{e}[:, None]"
        for d, e in decompose("r", red, x.shape).items():
            index[d] = f"{e}[None, :]"
        val = (f"tl.load({self.address(x, index, '(o[:, None] + r[None, :])')}, "
               f"mask=omask[:, None] & rmask[None, :], other={init})")
        if n.op == "reduce_sum":
            loop.emit(f"acc = acc + {val}")
            code.emit("res = tl.sum(acc, axis=1)")
        else:
            loop.emit(f"acc = tl.maximum(acc, {val})")
            code.emit("res = tl.max(acc, axis=1)")
        out_index = [None] * out.type.rank
        for d, e in decompose("o", kept, x.shape).items():
            out_index[d] = e
        code.emit(f"tl.store({self.address(out, out_index, 'o')}, res, mask=omask)")
        grid = (-(-n_out // bo),)
        return self.signature(name) + code.lines, Launch(name, grid, self.bases(), 4, None, "reduction", self.k.name)

    def matmul(self, name, config):
        mm = next(n for n in self.k.nodes if n.op == "matmul")
        a, b = mm.inputs
        batch = a.shape[:-2]
        m, k_, n_ = a.shape[-2], a.shape[-1], b.shape[-1]
        bm, bn, bk = config["BM"], config["BN"], config["BK"]
        code = _Code()
        code.emit("pid_m = tl.program_id(0)")
        code.emit("pid_n = tl.program_id(1)")
        code.emit("pid_b = tl.program_id(2)")
        if any(self.needs_int64(v) for v in self.inputs + self.outputs):
            code.emit("pid_b = pid_b.to(tl.int64)")
        code.emit(f"rm = pid_m * {bm} + tl.arange(0, {bm})")
        code.emit(f"rn = pid_n * {bn} + tl.arange(0, {bn})")
        code.emit(f"rk = tl.arange(0, {bk})")
        bidx, rest = [], "pid_b"
        for d in range(len(batch) - 1, -1, -1):
            if batch[d] == 1:
                bidx.append(None)
                continue
            stride = prod(batch[d + 1:])
            expr = f"({rest} // {stride})" if stride > 1 else rest
            bidx.append(f"({expr} % {batch[d]})" if d > 0 else expr)
        bidx.reverse()
        code.emit(f"acc = tl.zeros([{bm}, {bn}], dtype=tl.float32)")
        code.emit(f"for k0 in range(0, {k_}, {bk}):")
        loop = code.nested()
        a_ptr = self.address(a, bidx + ["rm[:, None]", "(k0 + rk)[None, :]"], "(rm[:, None] + rk[None, :])")
        b_ptr = self.address(b, bidx + ["(k0 + rk)[:, None]", "rn[None, :]"], "(rk[:, None] + rn[None, :])")
        loop.emit(f"av = tl.load({a_ptr}, mask=(rm[:, None] < {m}) & ((k0 + rk)[None, :] < {k_}), other=0.0)")
        loop.emit(f"bv = tl.load({b_ptr}, mask=((k0 + rk)[:, None] < {k_}) & (rn[None, :] < {n_}), other=0.0)")
        precision = "tf32" if self.allow_tf32 else "ieee"
        loop.emit(f'acc += tl.dot(av, bv, input_precision="{precision}")')
        code.emit(f"omask = (rm[:, None] < {m}) & (rn[None, :] < {n_})")
        index = bidx + ["rm[:, None]", "rn[None, :]"]
        tile = "(rm[:, None] + rn[None, :])"
        env = {mm.out: "acc"}
        load = lambda v: f"tl.load({self.address(v, index, tile)}, mask=omask, other=0.0)"
        self.compute(code, env, self.outputs, load)
        for v in self.outputs:
            code.emit(f"tl.store({self.address(v, index, tile)}, {self.operand(code, env, v, load)}, mask=omask)")
        nb = prod(batch) or 1
        grid = (-(-m // bm), -(-n_ // bn), nb)
        if grid[1] > 65535 or grid[2] > 65535:
            raise NotImplementedError(f"GPU backend: matmul grid {grid} exceeds CUDA limits")
        launch = Launch(name, grid, self.bases(), config["num_warps"], config["num_stages"], "matmul", self.k.name)
        return self.signature(name) + code.lines, launch

    def write(self, matmul_config):
        kind = self.k.kind
        if kind == "matmul":
            return [self.matmul(f"{self.k.name}_matmul", matmul_config(self.g, self.k))]
        if kind == "reduction":
            reductions = [n for n in self.k.nodes if n.op.startswith("reduce_")]
            if all(is_row_reduction(n) for n in reductions):
                return [self.row(f"{self.k.name}_row")]
            return [self.reduction(f"{self.k.name}_reduce")]
        # elementwise and copy: one Triton kernel per output shape
        return [self.elementwise(v, f"{self.k.name}_ew{i}") for i, v in enumerate(self.outputs)]


def v_offset_elements(lay):
    owner = lay.base[1]
    byte_offset = owner.node.attrs.get("offset", 0)
    assert byte_offset % 4 == 0
    return byte_offset // 4 + lay.offset


def sm_count():
    """Streaming multiprocessors on the GPU (170 on an RTX 5090); 128 under the interpreter."""
    import torch

    from kiln.gpu.runtime import interpreting

    if torch.cuda.is_available() and not interpreting():
        return torch.cuda.get_device_properties(0).multi_processor_count
    return 128


# Output tiles to try, largest first: bigger tiles reuse each loaded operand
# more, smaller ones make more programs to spread across the GPU.
TILES = [(128, 128), (128, 64), (64, 128), (64, 64), (64, 32), (32, 64), (32, 32), (16, 64), (32, 16),
         (16, 32), (16, 16)]   # 16 is tl.dot's minimum; (16, 16) fits any problem


def default_matmul_config(graph, kernel):
    """Tile sizes for a matmul kernel, without measuring.

    Take the largest output tile that still gives at least one program per
    SM. Large tiles are more efficient per program, but with 128 tokens a
    128 x 128 tile gives a single row of programs, about 18 for a 2304-wide
    projection, which leaves ~90% of a 170-SM GPU idle (measured on an RTX
    5090: 6.6 TFLOP/s with 128 x 128 tiles, 34.9 with the autotuner's choice).
    If even the smallest tile can't fill the GPU, the smallest one is used.

    fp32 operands at BK = 32 take (BM + BN) * BK * 4 bytes of shared memory
    per pipeline stage: 32 KiB for 128 x 128 (2 stages) and 16 KiB for 64 x 64
    (3 stages), within the ~100 KiB per block that consumer GPUs offer.
    """
    mm = next(n for n in kernel.nodes if n.op == "matmul")
    a, b = mm.inputs
    m, n = a.shape[-2], b.shape[-1]
    batch = 1
    for d in a.shape[:-2]:
        batch *= d
    sms = sm_count()
    fitting = [(bm, bn) for bm, bn in TILES if bm <= max(16, next_pow2(m)) and bn <= max(16, next_pow2(n))]
    bm, bn = fitting[-1]
    for tm, tn in fitting:
        if -(-m // tm) * -(-n // tn) * batch >= sms:
            bm, bn = tm, tn
            break
    warps = 8 if bm * bn >= 128 * 128 else 4
    stages = 2 if bm * bn >= 128 * 64 else 3
    return {"BM": bm, "BN": bn, "BK": 32, "num_warps": warps, "num_stages": stages}


def generate(graph: Graph, allow_tf32=False, matmul_config=default_matmul_config) -> Program:
    layouts = compute_layouts(graph)
    for k in graph.kernels:
        for n in k.nodes:
            if ops.kind(n.op) not in ("elementwise", "reduction", "matmul"):
                raise NotImplementedError(f"GPU backend: unexpected op '{n.op}' in a kernel")
    lines, launches = [PRELUDE], []
    for k in graph.kernels:
        for body, launch in _KernelWriter(graph, k, layouts, allow_tf32).write(matmul_config):
            lines.append("")
            lines.append("")
            lines.extend(body)
            launches.append(launch)
    return Program("\n".join(lines) + "\n", launches)